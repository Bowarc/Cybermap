class ZoomableGraphicsView(QGraphicsView):
    def __init__(self, rects):
        super().__init__()
        self.setRenderHints(self.renderHints())
        self.setTransformationAnchor(QGraphicsView.AnchorUnderMouse)
        self.setResizeAnchor(QGraphicsView.AnchorUnderMouse)
        self.setVerticalScrollBarPolicy(Qt.ScrollBarAlwaysOff)
        self.setHorizontalScrollBarPolicy(Qt.ScrollBarAlwaysOff)
        self.setFrameShape(QGraphicsView.NoFrame)
        self.setDragMode(QGraphicsView.ScrollHandDrag)

        self.initUI(rects)
        
    def initUI(self, rects):
        scene = QGraphicsScene(self)

        # Loop through the list of rectangles
        for index, (x, y, width, height) in enumerate(rects):

            print(f"{x}, {y}, {width}, {height}")
            
            if index == 0:
                # First rectangle: filled with green
                # 
                # QGraphicsRectItem expects topleft x, topleft y, width, height
                rect_item = QGraphicsRectItem(x - width / 2, y - height / 2, width, height)
                rect_item.setPen(QPen(QColor(255, 0, 0), 0, Qt.SolidLine, Qt.FlatCap))  # Red outline
                rect_item.setBrush(QBrush(QColor(0, 255, 0)))  # Green fill
            else:
                # Other rectangles: outline with red
                # 
                # QGraphicsRectItem expects topleft x, topleft y, width, height
                rect_item = QGraphicsRectItem(x - width / 2, y - height / 2, width, height)
                rect_item.setPen(QPen(QColor(255, 0, 0), 0, Qt.SolidLine, Qt.FlatCap))  # Red outline
                rect_item.setBrush(QBrush(QColor(255, 0, 0, 0)))  # Transparent fill
            
            scene.addItem(rect_item)

        self.setScene(scene)
        self.setWindowTitle('Rectangle List Example')
        self.setGeometry(300, 300, 400, 300)

        # self.fitInView(QRectF(*rects[0]), Qt.KeepAspectRatio) 

    def wheelEvent(self, event: QWheelEvent):
        factor = 1.25 if event.angleDelta().y() > 0 else 1 / 1.25

        current_scale = self.transform().m11()
        new_scale = current_scale * factor

        if 0.05 <= new_scale <= 50:
            self.scale(factor, factor)

        event.accept()
        
